/** 取扩展名（小写、不含点），无扩展名返回空串 */
export function getFileExt(name: string): string {
    const dotIdx = name.lastIndexOf('.');
    return dotIdx >= 0 ? name.slice(dotIdx + 1).toLowerCase() : '';
}

/**
 * 按文件名取图标：文件名映射优先，其次 .spec/.test 橙色变体，
 * 再按扩展名，未识别的扩展名回退 Seti 的 default 字形。
 */
export function getFileIcon(name: string): FileIconDef {
    const lower = name.toLowerCase();
    const byName = fileNameMap[lower];
    if (byName) return byName;
    const spec = /\.(?:spec|test)\.(\w+)$/.exec(lower);
    if (spec && specMap[spec[1]]) return specMap[spec[1]];
    return extMap[getFileExt(lower)] ?? def('default', 'white');
}
